"""Pydantic schemas for AI plan generation, proposals, and application."""

from datetime import UTC, datetime

from pydantic import Field

from app.schemas.budget import BudgetCategory
from app.schemas.common import BaseSchema
from app.schemas.task import TaskPriority
from app.schemas.vendor import VendorCategory


class AIBudgetItemProposal(BaseSchema):
    """Proposed item for event budget."""

    category: BudgetCategory = Field(..., description="Standard budget category")
    item_name: str = Field(..., min_length=2, max_length=150, description="Expense name")
    estimated_amount: float = Field(..., ge=0.0, description="Estimated allocation amount")
    notes: str | None = Field(
        default=None, max_length=500, description="Cost breakdown or reasoning"
    )


class AITaskProposal(BaseSchema):
    """Proposed planning task milestone."""

    title: str = Field(..., min_length=2, max_length=200, description="Task milestone title")
    category: str = Field(default="Milestone", max_length=50, description="Category")
    days_before_event: int = Field(
        ..., ge=0, le=730, description="Number of days prior to event date this should be completed"
    )
    priority: TaskPriority = Field(default=TaskPriority.MEDIUM, description="Task priority")
    description: str | None = Field(default=None, max_length=500, description="Task details")


class AIVendorCategoryProposal(BaseSchema):
    """Proposed vendor checklist requirement."""

    category: VendorCategory = Field(..., description="Vendor category")
    item_name: str = Field(..., min_length=2, max_length=150, description="Vendor requirement name")
    suggested_scope: str = Field(
        ..., min_length=2, max_length=500, description="Scope of services to request"
    )
    estimated_budget: float = Field(default=0.0, ge=0.0, description="Suggested target quote")


class AIPlanResponse(BaseSchema):
    """Structured AI event plan proposal."""

    event_id: str = Field(..., description="Associated event ID")
    summary: str = Field(..., min_length=10, description="Comprehensive event concept summary")
    theme_and_decor: list[str] = Field(
        default_factory=list, description="Visual styling, color palette, and decor ideas"
    )
    food_recommendations: list[str] = Field(
        default_factory=list, description="Curated culinary and beverage suggestions"
    )
    entertainment_suggestions: list[str] = Field(
        default_factory=list, description="Music, activities, and guest engagement concepts"
    )
    budget_allocations: list[AIBudgetItemProposal] = Field(
        default_factory=list, description="Itemized budget recommendations"
    )
    planning_tasks: list[AITaskProposal] = Field(
        default_factory=list, description="Chronological milestone timeline"
    )
    vendor_categories: list[AIVendorCategoryProposal] = Field(
        default_factory=list, description="Key vendor requirements"
    )
    personalized_recommendations: list[str] = Field(
        default_factory=list, description="Tips tailored to guest count, venue, and season"
    )
    provider_used: str = Field(default="sample", description="LLM provider name or sample")
    is_fallback: bool = Field(
        default=False, description="True if generated by deterministic offline fallback"
    )
    total_proposed_budget: float = Field(
        default=0.0, ge=0.0, description="Sum of proposed estimated allocations"
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC), description="Timestamp of generation"
    )


class AIPlanGenerateRequest(BaseSchema):
    """Options for AI plan generation."""

    focus_areas: list[str] | None = Field(
        default_factory=list, description="Optional areas of emphasis (decor, catering, etc.)"
    )
    force_fallback: bool = Field(
        default=False, description="Force deterministic sample provider for testing or offline mode"
    )
    event_context: dict | None = Field(
        default=None, description="Event context details passed directly from localStorage"
    )


class AIApplyPlanRequest(BaseSchema):
    """Request to persist and commit a generated AI plan proposal."""

    proposal: AIPlanResponse = Field(..., description="The plan proposal to commit")
    replace_existing: bool = Field(
        default=False,
        description="If True, removes existing uncommitted budget items, tasks, and vendors first",
    )


class AIApplyPlanResponse(BaseSchema):
    """Summary of committed items from plan application."""

    event_id: str
    budget_items_created: int
    tasks_created: int
    vendors_created: int
    message: str = "Plan successfully applied to event."
