"""Schemas for conversational AI assistant and targeted natural language modifications."""

from datetime import UTC, datetime
from typing import Literal

from pydantic import Field

from app.schemas.budget import BudgetCategory
from app.schemas.common import BaseSchema
from app.schemas.task import TaskPriority
from app.schemas.vendor import VendorCategory


class BudgetAdjustmentDiff(BaseSchema):
    """Specific budget modification item proposed by the assistant."""

    category: BudgetCategory = Field(..., description="Target budget category")
    action: Literal["decrease", "increase", "reallocate", "set"] = Field(
        ..., description="Modification action"
    )
    target_category: BudgetCategory | None = Field(
        default=None, description="Destination category for reallocations"
    )
    amount: float = Field(..., ge=0.0, description="Amount of change or new target")
    delta: float = Field(
        default=0.0, description="Net signed change in currency for this category"
    )
    reason: str = Field(default="", description="Reasoning or description of adjustment")


class TaskAdditionDiff(BaseSchema):
    """Task item proposed to be scheduled on the planning timeline."""

    title: str = Field(..., min_length=2, max_length=200, description="Task title")
    category: str = Field(default="Planning", max_length=50, description="Task category")
    due_date: str = Field(..., description="ISO 8601 formatted due date")
    priority: TaskPriority = Field(default=TaskPriority.MEDIUM, description="Task priority")
    description: str | None = Field(default=None, max_length=500, description="Task details")


class VendorAdditionDiff(BaseSchema):
    """Vendor requirement proposed by the assistant."""

    category: VendorCategory = Field(..., description="Vendor category")
    item_name: str = Field(..., min_length=2, max_length=150, description="Vendor requirement name")
    suggested_scope: str = Field(..., min_length=2, max_length=500, description="Scope of services")
    target_quote: float = Field(default=0.0, ge=0.0, description="Estimated target quote")


class EventUpdateDiff(BaseSchema):
    """Event-level parameter changes proposed by the assistant."""

    expected_guest_count: int | None = Field(default=None, ge=1, le=100000)
    total_budget: float | None = Field(default=None, ge=0.0)
    theme: str | None = Field(default=None, max_length=200)


class ProposedChanges(BaseSchema):
    """Structured collection of staged entity modifications."""

    budget_adjustments: list[BudgetAdjustmentDiff] = Field(
        default_factory=list, description="Proposed budget changes"
    )
    task_additions: list[TaskAdditionDiff] = Field(
        default_factory=list, description="Proposed timeline tasks"
    )
    vendor_additions: list[VendorAdditionDiff] = Field(
        default_factory=list, description="Proposed vendor requirements"
    )
    event_updates: EventUpdateDiff | None = Field(
        default=None, description="Proposed event meta modifications"
    )


class AssistantMessageRequest(BaseSchema):
    """Input user request sent to the conversational assistant."""

    prompt: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Natural language instruction, modification request, or question",
    )
    force_fallback: bool = Field(
        default=False,
        description="Force deterministic offline NLP parser for testing or offline mode",
    )
    event_context: dict | None = Field(default=None, description="Event details from localStorage")
    budget_items: list[dict] | None = Field(default=None, description="Budget items from localStorage")
    tasks: list[dict] | None = Field(default=None, description="Tasks from localStorage")
    vendors: list[dict] | None = Field(default=None, description="Vendors from localStorage")


class AssistantResponse(BaseSchema):
    """Assistant conversational reply, including any staged proposals requiring confirmation."""

    proposal_id: str | None = Field(
        default=None, description="Unique ID for staged proposed modifications"
    )
    reply: str = Field(..., description="Assistant conversational response or explanation")
    proposed_changes: ProposedChanges | None = Field(
        default=None, description="Structured diff of proposed modifications"
    )
    requires_confirmation: bool = Field(
        default=False,
        description="True if the assistant generated entity modifications that must be confirmed by user",
    )
    provider_used: str = Field(
        default="sample", description="Name of AI provider used (e.g. gemini-1.5-flash or sample)"
    )
    is_fallback: bool = Field(
        default=False, description="True if generated by deterministic offline heuristic parser"
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC), description="Timestamp of generation"
    )


class AssistantConfirmRequest(BaseSchema):
    """Confirmation payload to apply or reject a staged proposal."""

    confirmed: bool = Field(
        default=True, description="True to persist changes, False to dismiss proposal"
    )


class AssistantConfirmResponse(BaseSchema):
    """Result of confirming or dismissing a staged assistant proposal."""

    proposal_id: str
    applied: bool
    message: str
    budget_items_affected: int = 0
    tasks_created: int = 0
    vendors_created: int = 0
    event_updated: bool = False


class AssistantMessageLog(BaseSchema):
    """Persisted message in the event conversation history."""

    id: str
    event_id: str
    user_id: str
    role: Literal["user", "assistant"]
    content: str
    proposal_id: str | None = None
    created_at: datetime
